var LOCALES = ['fa', 'en', 'tr'];
var NATIVE_NAMES = {fa: 'فارسی', en: 'English', tr: 'Türkçe'};
var RTL = {fa: true};
var INTL_LOCALE = {fa: 'fa-IR', en: 'en-US', tr: 'tr-TR'};
var FALLBACK = 'en';
var DEFAULT_LOCALE = 'fa';
var STORE_KEY = 'af_locale';

var current = null;

// localStorage can throw (private mode, blocked storage): the UI must work without it.
function readStored(){
  try { var v = localStorage.getItem(STORE_KEY); return LOCALES.indexOf(v) >= 0 ? v : null; }
  catch (e){ return null; }
}
function writeStored(loc){
  try { localStorage.setItem(STORE_KEY, loc); } catch (e){}
}

function locale(){ return current || readStored() || DEFAULT_LOCALE; }
function isRtl(loc){ return !!RTL[loc || locale()]; }

function has(key){
  return Object.prototype.hasOwnProperty.call(MESSAGES[locale()], key) ||
    Object.prototype.hasOwnProperty.call(MESSAGES[FALLBACK], key);
}

// The text of `key` in the current language, English if it has none there, the key itself if neither has it.
// {name} placeholders take params.name; the result is always set as textContent, never as HTML.
function t(key, params){
  var text = MESSAGES[locale()][key];
  if (text === undefined) text = MESSAGES[FALLBACK][key];
  if (text === undefined) return key;
  if (params){
    text = text.replace(/\{(\w+)\}/g, function(match, name){
      var v = params[name];
      return v === undefined || v === null ? match : String(v);
    });
  }
  return text;
}

// `key` in a given language (the first-entry chooser greets in all three at once).
function tIn(loc, key){
  var table = MESSAGES[loc] || MESSAGES[FALLBACK];
  return table[key] !== undefined ? table[key] : (MESSAGES[FALLBACK][key] !== undefined ? MESSAGES[FALLBACK][key] : key);
}

function apply(){
  var loc = locale();
  document.documentElement.lang = loc;
  document.documentElement.dir = isRtl(loc) ? 'rtl' : 'ltr';
  var nodes = document.querySelectorAll('[data-i18n]');
  for (var i = 0; i < nodes.length; i++) nodes[i].textContent = t(nodes[i].getAttribute('data-i18n'));
}

// Switch the language of the whole UI; returns false (and changes nothing) for a language not offered.
function setLocale(loc){
  if (LOCALES.indexOf(loc) < 0) return false;
  current = loc;
  writeStored(loc);
  apply();
  return true;
}

function fmtNum(n){ return new Intl.NumberFormat(INTL_LOCALE[locale()]).format(n || 0); }
function fmtTime(iso){
  try { return new Date(iso).toLocaleString(INTL_LOCALE[locale()], {dateStyle: 'short', timeStyle: 'short'}); }
  catch (e){ return iso; }
}

window.I18N = {
  LOCALES: LOCALES, NATIVE_NAMES: NATIVE_NAMES,
  t: t, tIn: tIn, has: has, locale: locale, isRtl: isRtl, setLocale: setLocale, apply: apply,
  storedLocale: readStored, fmtNum: fmtNum, fmtTime: fmtTime
};

// Before app.js draws anything: the page opens in the remembered language and direction, no flash of the other.
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', apply);
else apply();
